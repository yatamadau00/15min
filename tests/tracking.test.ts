import assert from 'node:assert/strict';
import {transition,duration,clip,gaps} from '../lib/tracking.ts';
const t0=Date.parse('2026-11-13T23:55:00+09:00');
let result=transition(undefined,'start',t0,{runId:'test',title:'研究'});let t=result.timer;
assert.equal(t.end,t0+900000);
result=transition(t,'pause',t0+300000,{});t=result.timer;
assert.equal(duration(result.sessions[0].segments!),300000);assert.equal(t.remainingMs,600000);
result=transition(t,'start',t0+900000,{runId:'ignored'});t=result.timer;
assert.equal(t.end,t0+1500000);assert.equal(t.runId,'test');
result=transition(t,'settle',t0+86400000,{});t=result.timer;
const record=result.sessions[0];assert.equal(duration(record.segments!),900000);
assert.equal(record.segments![1].end,t0+1500000);
assert.equal(duration(clip(record.segments!,t0-86100000,t0+300000)),300000);
assert.equal(duration(clip(record.segments!,t0+300000,t0+86700000)),600000);
assert.equal(transition(t,'settle',t0+86400000,{}).sessions.length,0);
assert.equal(duration([{start:0,end:10},{start:5,end:15}]),15);
assert.deepEqual(gaps([{start:5,end:10}],0,20),[{start:0,end:5},{start:10,end:20}]);
result=transition(undefined,'start',0,{runId:'partial',title:'授業'});result=transition(result.timer,'reset',123000,{});
assert.equal(duration(result.sessions[0].segments!),123000);
assert.equal(result.timer.state,'idle');
const old:any={id:'shared-timer',kind:'timer',title:'旧',end:t0,remain:50,revision:123};
assert.equal(transition(old,'settle',t0+100000,{}).sessions[0].segments,undefined);
const live={...old,end:t0+600000,remain:600};
assert.equal(transition(live,'settle',t0,{}).timer.end,live.end);
assert.equal(transition({...old,end:null,remain:400},'settle',t0,{}).timer.remain,400);
console.log('PASS: pause/resume, delayed completion, midnight, overlap, gaps, partial reset, legacy');
